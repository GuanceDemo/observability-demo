import {createHash} from 'node:crypto';
import {readFile, writeFile, mkdir, copyFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import vm from 'node:vm';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const mobileRoot = path.resolve(scriptDirectory, '..');
const repositoryRoot = path.resolve(mobileRoot, '..');
const webAssetsRoot = path.join(
  repositoryRoot,
  'order-service/src/main/resources/static/assets',
);
const sourcePath = path.join(webAssetsRoot, 'selfheal-i18n.js');
const generatedPath = path.join(
  mobileRoot,
  'src/generated/storefrontData.generated.ts',
);
const nativeAssetRoot = path.join(mobileRoot, 'src/assets/storefront');
const bookContentPath = path.join(repositoryRoot, 'order-service/src/main/resources/mobile-book-content.json');
const checkOnly = process.argv.includes('--check');

const assetFiles = Object.freeze([
  'observability-engineering-zh.png',
  'observability-engineering-en.png',
  'avatars/demo-reader-a.png',
  'avatars/demo-reader-b.png',
  'avatars/demo-reader-c.png',
]);

function browserContext() {
  const window = {
    location: {href: 'http://localhost/shop.html'},
    localStorage: {
      getItem: () => null,
      setItem: () => undefined,
    },
    history: {replaceState: () => undefined, state: {}},
  };
  const document = {
    documentElement: {},
    querySelectorAll: () => [],
  };
  return {
    window,
    document,
    URL,
    Set,
    Object,
    Array,
    String,
    Number,
    Math,
    JSON,
    encodeURIComponent,
  };
}

function generatedSource(i18n, sourceHash) {
  const payload = {
    products: i18n.products,
    topics: i18n.topics,
    readingStages: i18n.readingStages,
    storeMessages: i18n.storeMessages,
  };
  return `// Generated by scripts/sync-storefront-data.mjs. Do not edit.\n` +
    `// Canonical source SHA-256: ${sourceHash}\n\n` +
    `export const storefrontCatalog = ${JSON.stringify(payload, null, 2)} as const;\n`;
}

async function filesEqual(leftPath, rightPath) {
  try {
    const [left, right] = await Promise.all([
      readFile(leftPath),
      readFile(rightPath),
    ]);
    return left.equals(right);
  } catch {
    return false;
  }
}

async function syncAssets() {
  const stale = [];
  for (const relativePath of assetFiles) {
    const source = path.join(webAssetsRoot, relativePath);
    const target = path.join(nativeAssetRoot, relativePath);
    if (checkOnly) {
      if (!(await filesEqual(source, target))) stale.push(relativePath);
      continue;
    }
    await mkdir(path.dirname(target), {recursive: true});
    await copyFile(source, target);
  }
  return stale;
}

async function main() {
  const source = await readFile(sourcePath, 'utf8');
  const context = browserContext();
  vm.runInNewContext(source, context, {filename: sourcePath});
  const i18n = context.window.SelfhealI18n;
  if (!i18n || !Array.isArray(i18n.products) || i18n.products.length === 0) {
    throw new Error('Canonical storefront data was not exported by SelfhealI18n.');
  }

  const sourceHash = createHash('sha256').update(source).digest('hex');
  const nextGenerated = generatedSource(i18n, sourceHash);
  const bookContent = JSON.stringify(Object.fromEntries(i18n.products.map(product => [product.id,
    Object.fromEntries(['zh', 'en'].map(language => [language, {
      bookId: product.id,
      title: product[language].title,
      description: product[language].description,
      parts: product[language].parts,
    }])),
  ])), null, 2) + '\n';
  const staleAssets = await syncAssets();

  if (checkOnly) {
    const currentGenerated = await readFile(generatedPath, 'utf8').catch(() => '');
    const currentContent = await readFile(bookContentPath, 'utf8').catch(() => '');
    if (currentGenerated !== nextGenerated || currentContent !== bookContent || staleAssets.length > 0) {
      const details = [
        currentGenerated !== nextGenerated ? 'generated TypeScript data' : '',
        currentContent !== bookContent ? 'server book content' : '',
        ...staleAssets.map(asset => `asset ${asset}`),
      ].filter(Boolean);
      throw new Error(
        `Native storefront source is stale: ${details.join(', ')}. Run npm run sync:storefront.`,
      );
    }
    console.log('Native storefront data and assets match the canonical Web source.');
    return;
  }

  await mkdir(path.dirname(generatedPath), {recursive: true});
  await writeFile(generatedPath, nextGenerated, 'utf8');
  await writeFile(bookContentPath, bookContent, 'utf8');
  console.log(`Generated ${path.relative(repositoryRoot, generatedPath)} from the canonical Web storefront.`);
}

main().catch(error => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
